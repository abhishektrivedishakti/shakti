import type { Driver as DbDriver } from '../generated/prisma';
import type { DocumentAttachment, Driver, FuelPolicy } from '../../src/types';
import { num, optBool, optNum, optStr, str } from './bodyParsers';
import { asJsonInput } from './jsonInput';

export function mapDbDriverToApi(row: DbDriver): Driver {
  return {
    id: row.id,
    driverCode: row.driverCode ?? undefined,
    name: row.name,
    phone: row.phone,
    alternatePhone: row.alternatePhone ?? undefined,
    address: row.address,
    licenseNumber: row.licenseNumber,
    licenseExpiry: row.licenseExpiry,
    badgeNumber: row.badgeNumber ?? undefined,
    policeVerificationDate: row.policeVerificationDate,
    policeVerificationExpiry: row.policeVerificationExpiry,
    aadharNumber: row.aadharNumber,
    panNumber: row.panNumber ?? undefined,
    bloodGroup: row.bloodGroup ?? undefined,
    joiningDate: row.joiningDate,
    monthlySalary: row.monthlySalary,
    dailyDaRate: row.dailyDaRate,
    status: row.status as Driver['status'],
    currentVehicleId: row.currentVehicleId ?? undefined,
    fuelPolicy: row.fuelPolicy as FuelPolicy,
    monthlyFuelBudgetAmount: row.monthlyFuelBudgetAmount,
    bankAccountDetails: row.bankAccountDetails ?? undefined,
    emergencyContact: row.emergencyContact ?? undefined,
    employmentType: (row.employmentType as Driver['employmentType']) ?? undefined,
    uanNumber: row.uanNumber ?? undefined,
    epfMemberId: row.epfMemberId ?? undefined,
    esicIpNumber: row.esicIpNumber ?? undefined,
    skillCategory: (row.skillCategory as Driver['skillCategory']) ?? undefined,
    minimumWageBasic: row.minimumWageBasic ?? undefined,
    vda: row.vda ?? undefined,
    hra: row.hra ?? undefined,
    isEpfApplicable: row.isEpfApplicable ?? undefined,
    isEsicApplicable: row.isEsicApplicable ?? undefined,
    documents: (row.documents as DocumentAttachment[] | null) ?? undefined,
  };
}

export function driverDataFromBody(body: Record<string, unknown>) {
  return {
    driverCode: optStr(body.driverCode),
    name: str(body.name),
    phone: str(body.phone),
    alternatePhone: optStr(body.alternatePhone),
    address: str(body.address),
    licenseNumber: str(body.licenseNumber),
    licenseExpiry: str(body.licenseExpiry),
    badgeNumber: optStr(body.badgeNumber),
    policeVerificationDate: str(body.policeVerificationDate),
    policeVerificationExpiry: str(body.policeVerificationExpiry),
    aadharNumber: str(body.aadharNumber),
    panNumber: optStr(body.panNumber),
    bloodGroup: optStr(body.bloodGroup),
    joiningDate: str(body.joiningDate),
    monthlySalary: num(body.monthlySalary),
    dailyDaRate: num(body.dailyDaRate),
    status: str(body.status, 'active') || 'active',
    currentVehicleId: optStr(body.currentVehicleId),
    fuelPolicy: str(body.fuelPolicy, 'actual_reimbursement') || 'actual_reimbursement',
    monthlyFuelBudgetAmount: num(body.monthlyFuelBudgetAmount),
    bankAccountDetails: optStr(body.bankAccountDetails),
    emergencyContact: optStr(body.emergencyContact),
    employmentType: optStr(body.employmentType),
    uanNumber: optStr(body.uanNumber),
    epfMemberId: optStr(body.epfMemberId),
    esicIpNumber: optStr(body.esicIpNumber),
    skillCategory: optStr(body.skillCategory),
    minimumWageBasic: optNum(body.minimumWageBasic),
    vda: optNum(body.vda),
    hra: optNum(body.hra),
    isEpfApplicable: optBool(body.isEpfApplicable),
    isEsicApplicable: optBool(body.isEsicApplicable),
    documents: asJsonInput(Array.isArray(body.documents) ? body.documents : body.documents ?? null),
  };
}
