import type { Vehicle as DbVehicle } from '../generated/prisma';
import type { DocumentAttachment, FuelPolicy, Vehicle, VehicleOperationalStatus } from '../../src/types';
import { num, optNum, optStr, str } from './bodyParsers';
import { asJsonInput } from './jsonInput';

export function mapDbVehicleToApi(row: DbVehicle): Vehicle {
  return {
    id: row.id,
    vehicleNumber: row.vehicleNumber,
    makeModel: row.makeModel,
    vehicleType: row.vehicleType as Vehicle['vehicleType'],
    fuelType: row.fuelType as Vehicle['fuelType'],
    color: row.color,
    modelYear: row.modelYear,
    ownershipType: row.ownershipType as Vehicle['ownershipType'],
    registrationType: (row.registrationType as Vehicle['registrationType']) ?? undefined,
    vendorId: row.vendorId ?? undefined,
    vendorName: row.vendorName ?? undefined,
    monthlyVendorRent: row.monthlyVendorRent ?? undefined,
    tenderId: row.tenderId,
    tenderPackageId: row.tenderPackageId ?? undefined,
    assignedOfficerId: row.assignedOfficerId ?? undefined,
    assignedOfficerName: row.assignedOfficerName ?? undefined,
    currentDriverId: row.currentDriverId ?? undefined,
    driverName: row.driverName ?? undefined,
    driverPhone: row.driverPhone ?? undefined,
    currentOdometer: row.currentOdometer,
    purchaseDate: row.purchaseDate ?? undefined,
    purchaseCost: row.purchaseCost ?? undefined,
    financingBank: row.financingBank ?? undefined,
    chassisNumber: row.chassisNumber ?? undefined,
    engineNumber: row.engineNumber ?? undefined,
    lastServiceDate: row.lastServiceDate ?? undefined,
    lastServiceKm: row.lastServiceKm ?? undefined,
    nextServiceDueKm: row.nextServiceDueKm ?? undefined,
    nextServiceDueDate: row.nextServiceDueDate ?? undefined,
    rtoFitnessExpiry: row.rtoFitnessExpiry,
    insuranceExpiry: row.insuranceExpiry,
    insuranceCompany: row.insuranceCompany ?? undefined,
    insurancePolicyNo: row.insurancePolicyNo ?? undefined,
    pucExpiry: row.pucExpiry,
    roadTaxExpiry: row.roadTaxExpiry,
    permitExpiry: row.permitExpiry,
    rcNumber: row.rcNumber ?? undefined,
    fitnessCertNumber: row.fitnessCertNumber ?? undefined,
    taxReceiptNumber: row.taxReceiptNumber ?? undefined,
    permitNumber: row.permitNumber ?? undefined,
    permitType: row.permitType ?? undefined,
    fastagId: row.fastagId ?? undefined,
    status: row.status as VehicleOperationalStatus,
    idleSinceDate: row.idleSinceDate ?? undefined,
    idleReason: row.idleReason ?? undefined,
    transferOrderRef: row.transferOrderRef ?? undefined,
    fuelPolicy: row.fuelPolicy as FuelPolicy,
    monthlyFixedFuelAmount: row.monthlyFixedFuelAmount ?? undefined,
    documents: (row.documents as DocumentAttachment[] | null) ?? undefined,
  };
}

export function vehicleDataFromBody(body: Record<string, unknown>) {
  return {
    vehicleNumber: str(body.vehicleNumber),
    makeModel: str(body.makeModel),
    vehicleType: str(body.vehicleType, 'Sedan') || 'Sedan',
    fuelType: str(body.fuelType, 'Diesel') || 'Diesel',
    color: str(body.color),
    modelYear: num(body.modelYear, 2024),
    ownershipType: str(body.ownershipType, 'Company Owned') || 'Company Owned',
    registrationType: optStr(body.registrationType),
    vendorId: optStr(body.vendorId),
    vendorName: optStr(body.vendorName),
    monthlyVendorRent: optNum(body.monthlyVendorRent),
    tenderId: str(body.tenderId),
    tenderPackageId: optStr(body.tenderPackageId),
    assignedOfficerId: optStr(body.assignedOfficerId),
    assignedOfficerName: optStr(body.assignedOfficerName),
    currentDriverId: optStr(body.currentDriverId),
    driverName: optStr(body.driverName),
    driverPhone: optStr(body.driverPhone),
    currentOdometer: num(body.currentOdometer),
    purchaseDate: optStr(body.purchaseDate),
    purchaseCost: optNum(body.purchaseCost),
    financingBank: optStr(body.financingBank),
    chassisNumber: optStr(body.chassisNumber),
    engineNumber: optStr(body.engineNumber),
    lastServiceDate: optStr(body.lastServiceDate),
    lastServiceKm: optNum(body.lastServiceKm),
    nextServiceDueKm: optNum(body.nextServiceDueKm),
    nextServiceDueDate: optStr(body.nextServiceDueDate),
    rtoFitnessExpiry: str(body.rtoFitnessExpiry),
    insuranceExpiry: str(body.insuranceExpiry),
    insuranceCompany: optStr(body.insuranceCompany),
    insurancePolicyNo: optStr(body.insurancePolicyNo),
    pucExpiry: str(body.pucExpiry),
    roadTaxExpiry: str(body.roadTaxExpiry),
    permitExpiry: str(body.permitExpiry),
    rcNumber: optStr(body.rcNumber),
    fitnessCertNumber: optStr(body.fitnessCertNumber),
    taxReceiptNumber: optStr(body.taxReceiptNumber),
    permitNumber: optStr(body.permitNumber),
    permitType: optStr(body.permitType),
    fastagId: optStr(body.fastagId),
    status: str(body.status, 'active') || 'active',
    idleSinceDate: optStr(body.idleSinceDate),
    idleReason: optStr(body.idleReason),
    transferOrderRef: optStr(body.transferOrderRef),
    fuelPolicy: str(body.fuelPolicy, 'actual_reimbursement') || 'actual_reimbursement',
    monthlyFixedFuelAmount: optNum(body.monthlyFixedFuelAmount),
    documents: asJsonInput(Array.isArray(body.documents) ? body.documents : body.documents ?? null),
  };
}
